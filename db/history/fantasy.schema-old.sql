    receiving_receptions INTEGER DEFAULT 0, -- NEW: From NFL_RESULTS.receivingrec
    receiving_yards INTEGER DEFAULT 0,
    receiving_tds INTEGER DEFAULT 0,
    receiving_twoptm INTEGER DEFAULT 0,     -- 2-point receiving conversions

    -- Offensive Misc/Contextual Statistics (from NFL_RESULTS)
    times_sacked INTEGER DEFAULT 0,
    fumbles_lost INTEGER DEFAULT 0,
    touch_carries INTEGER DEFAULT 0,
    touch_receptions INTEGER DEFAULT 0,
    touches INTEGER DEFAULT 0,
    targets_receptions INTEGER DEFAULT 0,
    targets INTEGER DEFAULT 0,
    reception_percentage NUMERIC(5,2) DEFAULT 0.00,
    rz_target INTEGER DEFAULT 0,
    rz_touch INTEGER DEFAULT 0,
    rz_g2g INTEGER DEFAULT 0,

    -- Kicking Statistics (from KICKER_RESULTS)
    pat_made INTEGER DEFAULT 0,             -- NEW: From KICKER_RESULTS.PatMade (extra points made)
    pat_missed INTEGER DEFAULT 0,           -- NEW: From KICKER_RESULTS.PatMissed (extra points missed)
    fg_made_0_19 INTEGER DEFAULT 0,         -- NEW: From KICKER_RESULTS.FgMade_0_19
    fg_made_20_29 INTEGER DEFAULT 0,        -- NEW: From KICKER_RESULTS.FgMade_20_29
    fg_made_30_39 INTEGER DEFAULT 0,        -- NEW: From KICKER_RESULTS.FgMade_30_39
    fg_made_40_49 INTEGER DEFAULT 0,        -- NEW: From KICKER_RESULTS.FgMade_40_49
    fg_made_50_plus INTEGER DEFAULT 0,      -- NEW: From KICKER_RESULTS.FgMade_50 (renamed for clarity)
    fg_miss_0_19 INTEGER DEFAULT 0,         -- NEW: From KICKER_RESULTS.FgMiss_0_19
    fg_miss_20_29 INTEGER DEFAULT 0,        -- NEW: From KICKER_RESULTS.FgMiss_20_29
    fg_miss_30_39 INTEGER DEFAULT 0,        -- NEW: From KICKER_RESULTS.FgMiss_30_39
