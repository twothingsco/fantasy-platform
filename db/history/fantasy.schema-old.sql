    tackles_assisted INTEGER DEFAULT 0,     -- NEW: From TacklesAst
    sacks_made NUMERIC(8,2) DEFAULT 0.00,   -- MODIFIED: From INTEGER to NUMERIC(8,2) to match TacklesSck
    tackles_for_loss INTEGER DEFAULT 0,     -- NEW: From TacklesTfl
