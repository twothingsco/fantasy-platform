CREATE TABLE match_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Offensive Passing Statistics
    passing_yards INTEGER DEFAULT 0,
    passing_tds INTEGER DEFAULT 0,
    passing_twoptm INTEGER DEFAULT 0,       -- 2-point conversions (general offensive, or specifically passing)
    interceptions_thrown INTEGER DEFAULT 0,

    -- Offensive Rushing Statistics
    rushing_yards INTEGER DEFAULT 0,
    rushing_tds INTEGER DEFAULT 0,
    rushing_twoptm INTEGER DEFAULT 0,       -- 2-point rushing conversions

