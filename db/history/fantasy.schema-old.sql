-- Table for League Settings
DROP TABLE IF EXISTS league_settings CASCADE;

CREATE TABLE league_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id INTEGER UNIQUE NOT NULL, -- Each league has one set of settings
    
    -- General Roster Settings
    total_roster_size INTEGER NOT NULL DEFAULT 16, -- Max players a team can have
    starting_lineup_size INTEGER NOT NULL DEFAULT 9, -- Number of players required in starting lineup
    bench_size INTEGER NOT NULL DEFAULT 7, -- Number of players on the bench

    -- Position Bucket Requirements (JSONB for flexibility)
    -- Example: {"QB": 1, "RB": 2, "WR": 2, "TE": 1, "FLEX": 1, "K": 1, "DEF": 1}
    starting_position_requirements JSONB NOT NULL DEFAULT '{}'::jsonb, 

    -- Scoring Mode (Reference to 'modes' table)
    mode_id INTEGER NOT NULL DEFAULT 1, -- Default to a standard mode, e.g., ID 1

    -- Draft Settings (assuming a snake draft for now)
    draft_type VARCHAR(255) NOT NULL DEFAULT 'Snake', -- 'Snake', 'Auction', 'Manual'
    draft_order_reversed_after_round BOOLEAN NOT NULL DEFAULT TRUE, -- For Snake draft
    picks_per_round INTEGER NOT NULL DEFAULT 1, -- Typically 1
    draft_start_date TIMESTAMP WITH TIME ZONE, -- When the draft officially opens
    draft_end_date TIMESTAMP WITH TIME ZONE,   -- When the draft officially closes

    -- Waiver Settings
    waiver_type VARCHAR(255) NOT NULL DEFAULT 'FAAB', -- 'FAAB', 'WaiverOrder', 'FirstComeFirstServe'
    faab_budget INTEGER NOT NULL DEFAULT 100, -- For FAAB waivers
    waiver_run_day VARCHAR(255) DEFAULT 'Wednesday', -- e.g., 'Wednesday', 'Tuesday'
    waiver_run_time TIME WITH TIME ZONE DEFAULT '03:00:00-07', -- e.g., 3:00 AM PST

    -- Trade Settings
    allow_trades BOOLEAN NOT NULL DEFAULT TRUE,
    trade_deadline TIMESTAMP WITH TIME ZONE,
    trade_review_period_hours INTEGER DEFAULT 24, -- Hours for league review before trade processes

    -- Playoff Settings
    playoff_start_week INTEGER, -- The game_week.number when playoffs begin
    num_playoff_teams INTEGER,
    championship_week INTEGER, -- The game_week.number for the championship game

    -- League State/Status
    league_status VARCHAR(255) NOT NULL DEFAULT 'Drafting', -- 'Pre-Draft', 'Drafting', 'Regular Season', 'Playoffs', 'Completed'

    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    -- Foreign Key Constraint
    CONSTRAINT fk_league_settings_league
        FOREIGN KEY (league_id) REFERENCES leagues(id) ON DELETE CASCADE,
    CONSTRAINT fk_league_settings_mode
        FOREIGN KEY (mode_id) REFERENCES modes(id) ON DELETE RESTRICT -- Don't delete a mode if leagues use it
);

CREATE INDEX index_league_settings_on_league_id ON league_settings (league_id);
CREATE INDEX index_league_settings_on_mode_id ON league_settings (mode_id);

CREATE TRIGGER set_updated_at_league_settings
BEFORE UPDATE ON league_settings
FOR EACH ROW
EXECUTE FUNCTION update_timestamp();